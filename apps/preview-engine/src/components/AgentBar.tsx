"use client";

import { useState } from "react";

type TierId = "SANJI_EXPRESS_290" | "SANJI_CORE_1200";

interface Receipt {
  buybackTxSignature: string;
  solscanUrl: string;
  bountyId: string;
  updatedStatus: string;
  mode: "live" | "simulated";
  buybackSol: number;
  bountyUsdc: number;
  detail: string;
  bountyDetail?: string;
}

const TIERS: Array<{ id: TierId; amountUsd: number; label: string }> = [
  { id: "SANJI_EXPRESS_290", amountUsd: 290, label: "Activar Sanji Express ($290 USD)" },
  { id: "SANJI_CORE_1200", amountUsd: 1200, label: "Activar Autonomous Core ($1,200 USD)" },
];

export function AgentBar({
  slug,
  name,
  gatewayUrl,
}: {
  slug: string;
  name: string;
  gatewayUrl: string;
}) {
  const [pending, setPending] = useState<TierId | null>(null);
  const [receipt, setReceipt] = useState<Receipt | null>(null);
  const [error, setError] = useState<string | null>(null);

  async function activate(tier: TierId, amountUsd: number) {
    setPending(tier);
    setError(null);
    try {
      const response = await fetch(`${gatewayUrl}/api/webhooks/payment-confirmed`, {
        method: "POST",
        headers: {
          "content-type": "application/json",
          "x-demo-simulation": "true",
        },
        body: JSON.stringify({ slug, tier, amountUsd }),
      });
      const body = (await response.json()) as Receipt & { error?: string };
      if (!response.ok) {
        setReceipt(null);
        setError(body.error ?? `El gateway respondió HTTP ${response.status}.`);
        return;
      }
      setReceipt(body);
    } catch {
      setError("No llegué al gateway en el puerto 4000. ¿Está corriendo pnpm dev?");
    } finally {
      setPending(null);
    }
  }

  return (
    <div className="sticky top-0 z-40 border-b border-white/10 bg-obsidian/95 backdrop-blur">
      <div className="mx-auto flex max-w-6xl flex-col gap-3 px-4 py-3 md:flex-row md:items-center md:justify-between md:px-6">
        <div className="min-w-0">
          <p className="flex items-center gap-2 font-mono text-[11px] uppercase tracking-[0.18em] text-cream">
            <span className="live-dot inline-block h-1.5 w-1.5 rounded-full bg-ember" aria-hidden />
            ⚡ GENERATED BY SANJI AI AGENT (x402 VERIFIED)
          </p>
          <p className="mt-1 truncate text-sm text-ash">{name}</p>
        </div>
        <div className="flex flex-col gap-2 sm:flex-row">
          {TIERS.map((tier) => (
            <button
              key={tier.id}
              type="button"
              disabled={pending !== null}
              onClick={() => activate(tier.id, tier.amountUsd)}
              className="min-h-11 bg-ember px-4 py-2 text-left text-sm font-medium text-obsidian transition hover:bg-cream disabled:cursor-wait disabled:opacity-60"
            >
              {pending === tier.id ? "Activando…" : tier.label}
            </button>
          ))}
        </div>
      </div>
      {error ? (
        <p className="border-t border-white/10 px-4 py-3 font-mono text-xs text-ember md:px-6" role="alert">
          {error}
        </p>
      ) : null}
      {receipt ? (
        <aside className="border-t border-ember/40 bg-soot px-4 py-4 md:px-6" aria-live="polite">
          <p className="font-mono text-[11px] uppercase tracking-[0.18em] text-ember">
            {receipt.mode === "live" ? "Buyback emitido" : "Recibo de demo"} · {receipt.updatedStatus}
          </p>
          <dl className="mt-3 grid gap-3 font-mono text-xs text-cream sm:grid-cols-3">
            <div>
              <dt className="text-ash">Buyback</dt>
              <dd className="mt-1">{receipt.buybackSol} SOL</dd>
              <dd className="mt-1 break-all text-ash">{receipt.buybackTxSignature}</dd>
            </div>
            <div>
              <dt className="text-ash">Bounty</dt>
              <dd className="mt-1">${receipt.bountyUsdc} USDC</dd>
              <dd className="mt-1 break-all">{receipt.bountyId}</dd>
            </div>
            <div>
              <dt className="text-ash">Solscan</dt>
              <dd className="mt-1 break-all">
                {receipt.solscanUrl ? (
                  <a className="underline decoration-ember underline-offset-4" href={receipt.solscanUrl}>
                    {receipt.solscanUrl}
                  </a>
                ) : (
                  "Sin broadcast. Falta la key del agente o el mint."
                )}
              </dd>
            </div>
          </dl>
          <p className="mt-3 max-w-3xl text-sm text-ash">{receipt.detail}</p>
        </aside>
      ) : null}
    </div>
  );
}
